const fs = require('fs')
const path = require('path')
const readline = require('readline')

const OUTPUT = path.resolve(process.env.SIVA_WORKER_ENV_FILE || '.env.local-worker')

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
})

function ask(question, fallback = '') {
  return new Promise(resolve => {
    rl.question(fallback ? question + ' [' + fallback + '] ' : question + ' ', answer => {
      resolve(String(answer || fallback).trim())
    })
  })
}

function askSecret(question) {
  return new Promise(resolve => {
    rl.question(question + ' ', answer => resolve(String(answer || '')))
  })
}

function quote(value) {
  return JSON.stringify(String(value || ''))
}

async function main() {
  console.log('\nRAILX local worker setup')
  console.log('This creates a local-only env file. It does not upload credentials to GitHub.\n')

  const controlUrl = await ask('Render control-plane URL', 'https://irctc-dashboard.onrender.com')
  const token = await askSecret('SIVA_WORKER_TOKEN (copy the value configured on Render):')
  const account = await ask('IRCTC account username:')
  const password = await askSecret('IRCTC account password:')

  if (!controlUrl || !token || !account || !password) {
    throw new Error('Control URL, worker token, username, and password are required.')
  }

  const env = [
    '# Generated by npm run setup:local-worker',
    '# Keep this file private. It is ignored by git.',
    'SIVA_CONTROL_URL=' + quote(controlUrl),
    'SIVA_WORKER_TOKEN=' + quote(token),
    'SIVA_WORKER_ACCOUNT=' + quote(account),
    'IRCTC_USERNAME=' + quote(account),
    'IRCTC_PASSWORD=' + quote(password),
    'SIVA_WORKER_CONCURRENCY=1',
    '',
  ].join('\n')

  fs.writeFileSync(OUTPUT, env, { mode: 0o600 })
  console.log('\nCreated ' + OUTPUT)
  console.log('Start the worker with:')
  console.log('  npm run start:local-worker')
  console.log('\nThe worker automatically loads .env.local-worker and must remain running on the machine that owns the IRCTC browser session.')
}

main()
  .catch(error => {
    console.error('[SETUP] ' + error.message)
    process.exitCode = 1
  })
  .finally(() => rl.close())
